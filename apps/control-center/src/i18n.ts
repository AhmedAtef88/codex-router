const MESSAGES: Record<LanguageId, Overlay> = {
  en: EN,
  "zh-CN": ZH,
  ar: AR,
  hi: HI,
  ja: JA,
  ko: KO,
};

export function isLanguageId(value: unknown): value is LanguageId {
  return LANGUAGE_OPTIONS.some((option) => option.id === value);
}

export function languageOption(language: LanguageId) {
  return LANGUAGE_OPTIONS.find((option) => option.id === language) ?? LANGUAGE_OPTIONS[0];
}

// A stored answer is the operator's own and is returned verbatim. Only when
// nobody has answered do we read the browser's preference, matching how the
// Tauri panel picks a first language.
export function detectLanguage(): LanguageId {
  try {
    const stored = localStorage.getItem(LANGUAGE_STORAGE_KEY);
    if (isLanguageId(stored)) return stored;
  } catch { /* storage can be unavailable; fall through to the browser hint */ }
  const navigatorLanguage = typeof navigator === "undefined" ? "" : navigator.language || "";
  if (/^zh/i.test(navigatorLanguage)) return "zh-CN";
  const prefix = navigatorLanguage.split("-")[0]?.toLowerCase();
  return isLanguageId(prefix) ? prefix : "en";
}

export function storeLanguage(language: LanguageId): void {
  try {
    localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
  } catch { /* a rejected write only costs the preference on next launch */ }
}

export function applyDocumentLanguage(language: LanguageId): void {
  const option = languageOption(language);
  const root = document.documentElement;
  root.lang = option.locale;
  root.dir = "dir" in option && option.dir === "rtl" ? "rtl" : "ltr";
}

export function translate(
  language: LanguageId,
  key: MessageKey,
  values: Record<string, string | number> = {},
): string {
  const template = MESSAGES[language]?.[key] ?? EN[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in values ? String(values[name]) : match);
}

export type Translate = (key: MessageKey, values?: Record<string, string | number>) => string;
